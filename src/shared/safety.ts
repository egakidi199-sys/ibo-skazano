// Эвристика «тезис оправдывает насилие над другими» (design D7). Отказов нет:
// такой ответ лишь помечается как чувствительный — подбор идёт по обеим сторонам,
// контекст раскрыт, показывается оговорка. Дополняет суждение модели (поле sensitive)
// и работает в fallback, где модели нет.

import { normalizeWord, tokenize } from "./stem";

// Физическое насилие над людьми.
const VIOLENT = new Set([
  "бить", "бьют", "бей", "бейте", "побить", "избить", "избивать", "ударить", "ударять", "бил", "била", "били",
  "убить", "убивать", "убей", "пытать", "изнасиловать", "выпороть", "пороть", "отлупить", "лупить", "покалечить",
  "искалечить", "казнить", "линчевать", "сжечь", "травить", "затравить", "истребить", "истреблять",
]);

// Слова, превращающие высказывание в оправдание («можно», «нужно», «заслуживает»).
const JUSTIFY = new Set([
  "можно", "нужно", "надо", "следует", "стоит", "должен", "должна", "должны", "вправе", "право", "допустимо",
  "позволено", "позволительно", "правильно", "оправдано", "полезно", "заслуживает", "заслуживают", "положено",
]);

// Контекст самообороны — не оправдание вреда.
const SELF_DEFENSE = /самооборон|защищая|защитить себя|защищаться/;

const WINDOW = 4;

export function isHarmJustification(...texts: string[]): boolean {
  const text = normalizeWord(texts.join(" \n "));
  if (SELF_DEFENSE.test(text)) return false;

  const words = tokenize(text); // однобуквенные отброшены, «не» и «ни» остаются
  for (let i = 0; i < words.length; i++) {
    if (!JUSTIFY.has(words[i])) continue;
    if (words[i - 1] === "не" || words[i - 1] === "ни") continue; // «не нужно бить»
    const from = Math.max(0, i - WINDOW);
    const to = Math.min(words.length - 1, i + WINDOW);
    for (let j = from; j <= to; j++) {
      if (j !== i && VIOLENT.has(words[j]) && words[j - 1] !== "не") return true;
    }
  }
  return false;
}
