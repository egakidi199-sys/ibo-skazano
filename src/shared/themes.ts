// Курируемый тематический указатель для подбора без LLM (fallback-search, design D6).
//
// У темы есть утверждение (claim). stance у ссылки — отношение стиха к этому
// утверждению: "confirm" — стих его поддерживает, "refute" — возражает.
// triggers — слова, по которым тема узнаётся в запросе; claimWords — подмножество слов,
// выражающих само утверждение: по отрицанию рядом с ними определяется, согласен ли
// тезис пользователя с утверждением темы (см. fallback.ts).
// Все ссылки — в синодальной нумерации; целостность проверяет themes.test.ts.

export type ThemeStance = "confirm" | "refute";

export interface ThemeRef {
  ref: string;
  stance: ThemeStance;
}

export interface Theme {
  id: string;
  title: string;
  claim: string;
  triggers: readonly string[];
  claimWords: readonly string[];
  refs: readonly ThemeRef[];
}

const c = (ref: string): ThemeRef => ({ ref, stance: "confirm" });
const r = (ref: string): ThemeRef => ({ ref, stance: "refute" });

